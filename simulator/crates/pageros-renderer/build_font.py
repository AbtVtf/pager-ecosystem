# Build the byte table.
chars = sorted(G.keys())
expected = [chr(c) for c in range(0x20, 0x7f)]
missing = [c for c in expected if c not in G]
extra = [c for c in chars if c not in expected]
assert not missing, f"missing glyphs: {missing!r}"
assert not extra, f"unexpected glyphs: {extra!r}"

table = []
for c in expected:
    rows = G[c]
    bytes_ = []
    for r in rows:
        b = 0
        for i, px in enumerate(r):  # leftmost = bit 4
            if px == '#':
                b |= (1 << (4 - i))
        bytes_.append(b)
    table.append((c, bytes_))

out = []
out.append("// Auto-generated by build_font.py. Do not edit by hand.")
out.append("// 5x7 ASCII bitmap font, printable range 0x20..=0x7E.")
out.append("// Each glyph: 7 bytes (one per row, top→bottom).")
out.append("// Within a byte: bit 4 (0x10) is the leftmost column, bit 0 the rightmost.")
out.append("")
out.append("pub const GLYPH_WIDTH: u32 = 5;")
out.append("pub const GLYPH_HEIGHT: u32 = 7;")
out.append("pub const FIRST_CODEPOINT: u8 = 0x20;")
out.append("pub const LAST_CODEPOINT: u8 = 0x7E;")
out.append("")
out.append("pub static FONT_5X7: [[u8; 7]; 95] = [")
for c, bytes_ in table:
    label = repr(c)
    out.append(f"    [{', '.join(f'0x{b:02X}' for b in bytes_)}], // {label}")
out.append("];")
out.append("")

dst = os.path.join(os.path.dirname(__file__), "src", "font_data.rs")
with open(dst, "w") as f:
    f.write("\n".join(out))
print(f"wrote {dst} ({sum(7 for _ in table)} bytes of glyph data, {len(table)} chars)")
