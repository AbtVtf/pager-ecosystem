# --- Emitter --------------------------------------------------------- #

def parse_glyph(art):
    """Convert ASCII-art block into a list of 16 row bitmaps (uint16)."""
    lines = [l for l in art.splitlines() if l.strip() != ""]
    # Allow indented blocks by stripping common leading whitespace per line,
    # but only spaces (so '.'-padded blocks keep their alignment).
    out = []
    for i in range(GLYPH_H):
        if i < len(lines):
            row = lines[i]
        else:
            row = "." * GLYPH_W
        # If the row is exactly GLYPH_W chars, use as-is. Otherwise pad or
        # truncate, treating both '.' and ' ' as empty and '#'/'X' as filled.
        row = row.replace(" ", ".")
        if len(row) < GLYPH_W:
            row = row + "." * (GLYPH_W - len(row))
        elif len(row) > GLYPH_W:
            row = row[:GLYPH_W]
        bits = 0
        for col in range(GLYPH_W):
            c = row[col]
            on = (c == "#" or c == "X")
            if on:
                # MSB is leftmost pixel
                bits |= (1 << (GLYPH_W - 1 - col))
        out.append(bits)
    return out


def emit_header(path: Path):
    # Build a 128-entry table for ASCII; 16-entry sub-table per row.
    # Plus a "supplemental" table for the few Unicode codepoints we draw
    # in the chrome (●, ◌, ▓, ▒, █, ▶, ▸).
    ascii_glyphs = {}
    supplemental = {}
    for ch, art in GLYPHS.items():
        cp = ord(ch)
        rows = parse_glyph(art)
        if cp < 128:
            ascii_glyphs[cp] = rows
        else:
            supplemental[cp] = rows

    lines = []
    lines.append("// SPDX-License-Identifier: Apache-2.0")
    lines.append("//")
    lines.append("// Generated by firmware/components/fonts/tools/gen_font16x16.py")
    lines.append("// DO NOT EDIT BY HAND — re-run the generator instead.")
    lines.append("")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append(f"#define PAGEROS_FONT16_W {GLYPH_W}")
    lines.append(f"#define PAGEROS_FONT16_H {GLYPH_H}")
    lines.append("")
    # ASCII table (128 entries; missing slots zero-filled).
    lines.append("// 16x16 ASCII bitmap. Each glyph is 16 rows of 16 bits;")
    lines.append("// bit 15 (MSB) is the leftmost pixel. Codepoints not designed")
    lines.append("// have all rows == 0 and are flagged absent in the present[] bitmap.")
    lines.append("static const uint16_t pageros_font16_ascii[128][16] = {")
    for cp in range(128):
        rows = ascii_glyphs.get(cp)
        if rows is None:
            lines.append(f"    [0x{cp:02X}] = {{ 0 }},")
        else:
            hexrows = ", ".join(f"0x{r:04X}" for r in rows)
            label = chr(cp) if (32 <= cp < 127 and chr(cp) != '\\') else f"\\x{cp:02X}"
            lines.append(f"    [0x{cp:02X}] = {{ {hexrows} }},  // '{label}'")
    lines.append("};")
    lines.append("")
    # Present bitmap (16 bytes = 128 bits).
    lines.append("// 1 bit per ASCII codepoint — set means a designed glyph exists.")
    lines.append("static const uint8_t pageros_font16_ascii_present[16] = {")
    for byte_i in range(16):
        bits = 0
        for bit_i in range(8):
            cp = byte_i * 8 + bit_i
            if cp in ascii_glyphs:
                bits |= (1 << bit_i)
        lines.append(f"    0x{bits:02X},")
    lines.append("};")
    lines.append("")
    # Supplemental Unicode table.
    lines.append("// Supplemental glyphs for chrome (non-ASCII).")
    lines.append("typedef struct {")
    lines.append("    uint32_t codepoint;")
    lines.append("    uint16_t rows[16];")
    lines.append("} pageros_font16_supp_t;")
    lines.append("")
    lines.append("static const pageros_font16_supp_t pageros_font16_supp[] = {")
    for cp in sorted(supplemental):
        rows = supplemental[cp]
        hexrows = ", ".join(f"0x{r:04X}" for r in rows)
        lines.append(f"    {{ 0x{cp:04X}, {{ {hexrows} }} }},  // U+{cp:04X}")
    lines.append("};")
    lines.append("")
